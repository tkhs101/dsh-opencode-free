// T2: inline the freeModels() baseline ids into src/client.js.
//
// Reads freeModels().map(id) and idempotently rewrites the MODELS block in
// src/client.js (between the <gen-client-models> markers). When
// src/client.js does not exist yet (T3 has not created it), the script only
// prints the MODELS JSON to stdout so T3 can hard-code the placeholder.
//
// Runnable both ways:
//   node scripts/gen-client-models.mjs                      (reads ../lib, needs a prior build)
//   tsx scripts/gen-client-models.mjs                       (reads ../src, used by prebuild)
const MARK_BEGIN = "<gen-client-models:begin>";
const MARK_END = "<gen-client-models:end>";

let freeModels;
try {
  ({ freeModels } = await import("../src/zen-provider.ts"));
} catch {
  ({ freeModels } = await import("../lib/zen-provider.js"));
}

const ids = freeModels().map((m) => m.id);
console.log(JSON.stringify(ids));

const { existsSync, readFileSync, writeFileSync } = await import("node:fs");
const { resolve, dirname } = await import("node:path");
const { fileURLToPath } = await import("node:url");

const clientPath = resolve(dirname(fileURLToPath(import.meta.url)), "../src/client.js");
if (!existsSync(clientPath)) {
  console.error(`[gen-client-models] ${clientPath} missing; printed MODELS JSON only (T3 placeholder).`);
  process.exit(0);
}

const block = [
  `// ${MARK_BEGIN} — auto-generated by scripts/gen-client-models.mjs, do not hand-edit.`,
  `var MODELS = ${JSON.stringify(ids, null, 2)};`,
  `// ${MARK_END}`,
].join("\n");

const text = readFileSync(clientPath, "utf8");
const re = new RegExp(`// ${MARK_BEGIN}[\\s\\S]*?// ${MARK_END}`);
if (!re.test(text)) {
  console.error("[gen-client-models] markers not found in src/client.js; leaving file untouched.");
  process.exit(1);
}
const next = text.replace(re, () => block);
if (next !== text) writeFileSync(clientPath, next);
console.error(`[gen-client-models] MODELS updated (${ids.length} ids).`);
